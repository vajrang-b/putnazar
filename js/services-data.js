/**
 * Filter villains list by language
 */
export function filterVillainsByLanguage(list, language) {
  if (!language || language.toLowerCase() === "all") return [...list];
  const target = language.toLowerCase();
  return list.filter(v => v.language.toLowerCase() === target);
}

/**
 * Sort villains list
 */
export function sortVillains(list, sortKey) {
  const sorted = [...list];
  switch (sortKey) {
    case "chrono-asc":
      return sorted.sort((a, b) => a.year - b.year);
    case "chrono-desc":
      return sorted.sort((a, b) => b.year - a.year);
    case "name-asc":
      return sorted.sort((a, b) => a.name.localeCompare(b.name));
    case "danger":
      return sorted.sort((a, b) => b.id.localeCompare(a.id));
    default:
      return sorted;
  }
}

/**
 * Generate an interactive Occult Service Pact
 */
export function generatePact(villain, targetName = "Unknown Entity", customService = "") {
  const cleanTarget = targetName.trim() || "Nameless Adversary";
  const pactService = customService || villain.service;
  const randNum = Math.floor(1000 + Math.random() * 9000);
  const langCode = villain.language.slice(0, 3).toUpperCase();
  const pactId = `PACT-${langCode}-${villain.year}-${randNum}`;

  return {
    pactId,
    villainId: villain.id,
    villainName: villain.name,
    actor: villain.actor,
    movie: villain.movie,
    language: villain.language,
    year: villain.year,
    target: cleanTarget,
    service: pactService,
    incantation: villain.incantation,
    offering: villain.offering,
    burnUrl: `./?burn=${encodeURIComponent(villain.image)}&target=${encodeURIComponent(cleanTarget)}&master=${encodeURIComponent(villain.name)}`,
    issuedAt: new Date().toISOString(),
  };
}
